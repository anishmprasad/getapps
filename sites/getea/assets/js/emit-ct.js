    "    double[] e3 = hEmaOn(hEmaOn(hEmaSeries(per, ap, sh, 12, false), per), per);",
    "    int n = e3.Length;",
    "    if (n < 3 || e3[n - 2] == 0) return 0;",
    "    return (e3[n - 1] - e3[n - 2]) / e3[n - 2] * 10000.0;",
    "}",

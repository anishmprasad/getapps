    "}",
    "private double hHma(int per, int ap, int sh)",
    "{",
    "    int half = (int)System.Math.Max(1, System.Math.Round(per / 2.0));",
    "    int root = (int)System.Math.Max(1, System.Math.Round(System.Math.Sqrt((double)per)));",
    "    double s = 0, w = 0;",
    "    for (int j = 0; j < root; j++)",
    "    {",
    "        double raw = 2.0 * hWma(half, ap, sh + j) - hWma(per, ap, sh + j);",
    "        double k = root - j; s += raw * k; w += k;",
    "    }",
    "    return w > 0 ? s / w : 0;",
    "}",

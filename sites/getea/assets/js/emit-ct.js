    "}",
    "/* sel: 0 width %, 1 %B */",
    "private double hBbw(int per, double dev, int ap, int sh, int sel)",
    "{",
    "    double m = hSma(per, ap, sh), sd = hStdDev(per, ap, sh);",
    "    double up = m + dev * sd, lo = m - dev * sd;",
    "    if (sel == 1) return (up - lo) > 0 ? (pAp(ap, sh) - lo) / (up - lo) * 100.0 : 0;",

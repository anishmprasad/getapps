    "{",
    "    double[] e1 = hEmaSeries(per, ap, sh, 8, false);",
    "    double[] e2 = hEmaOn(e1, per);",
    "    int n = e1.Length;",
    "    return 2.0 * e1[n - 1] - e2[n - 1];",
    "}",
    "private double hTema(int per, int ap, int sh)",
    "{",
    "    double[] e1 = hEmaSeries(per, ap, sh, 10, false);",
    "    double[] e2 = hEmaOn(e1, per);",
    "    double[] e3 = hEmaOn(e2, per);",
    "    int n = e1.Length;",
    "    return 3.0 * e1[n - 1] - 3.0 * e2[n - 1] + e3[n - 1];",
    "}",
